-- 3. Перегрузка fn_issue_electronic_passport на 7 параметров
CREATE OR REPLACE FUNCTION app.fn_issue_electronic_passport(
    p_citizen_id BIGINT,
    p_series VARCHAR,
    p_number VARCHAR,
    p_chip_uid VARCHAR,
    p_issuing_authority_code VARCHAR,
    p_issue_date VARCHAR,
    p_expiry_date VARCHAR
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = app, ref, audit, public, pg_temp
AS $$
DECLARE
    v_raw BYTEA := ('CHIP_PAYLOAD_' || p_chip_uid)::bytea;
    v_clean_code VARCHAR := p_issuing_authority_code;
BEGIN
    IF v_clean_code LIKE 'MVD-%' THEN
        v_clean_code := substr(v_clean_code, 5);
    END IF;

    RETURN app.fn_issue_electronic_passport(
        p_citizen_id,
        'E_PASSPORT',
        p_series,
        p_number,
        v_clean_code,
        10,
        v_raw,
        'AutoGeneratedMasterKey'
    );
END;
$$;

GRANT EXECUTE ON FUNCTION app.fn_issue_electronic_passport(BIGINT, VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR) TO app_writer, dml_admin;

-- 4. Перегрузка fn_register_biometric_template с поддержкой FINGERPRINT и байт/текста
CREATE OR REPLACE FUNCTION app.fn_register_biometric_template(
    p_citizen_id BIGINT,
    p_modality_code VARCHAR,
    p_template_raw BYTEA,
    p_quality_score NUMERIC,
    p_capture_device_id VARCHAR,
    p_encryption_key TEXT
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = app, ref, audit, public, pg_temp
AS $$
DECLARE
    v_mod VARCHAR := CASE WHEN p_modality_code = 'FINGERPRINT' THEN 'FINGERPRINT_SLAP' ELSE p_modality_code END;
    v_raw BYTEA := p_template_raw;
    v_modality_id INT;
    v_template_hash VARCHAR(64);
    v_encrypted_data BYTEA;
    v_new_biometric_id BIGINT;
    v_start_time TIMESTAMPTZ := clock_timestamp();
    v_exec_ms NUMERIC(10,3);
    v_params JSONB;
BEGIN
    v_params := jsonb_build_object(
        'citizen_id', p_citizen_id,
        'modality', v_mod,
        'quality_score', p_quality_score,
        'device_id', p_capture_device_id
    );

    IF p_quality_score < 50.00 THEN
        RAISE EXCEPTION 'Недопустимое качество биометрического сэмпла: % (требуется от 50.00 до 100.00 баллов)', p_quality_score;
    END IF;

    -- Если длина меньше 32 байт, дополняем для прохождения валидации
    IF length(v_raw) < 32 THEN
        v_raw := v_raw || decode(repeat('00', 32 - length(v_raw)), 'hex');
    END IF;

    SELECT modality_id INTO v_modality_id
    FROM ref.biometric_modalities
    WHERE code = v_mod;

    v_template_hash := encode(digest(v_raw, 'sha256'), 'hex');
    v_encrypted_data := pgp_sym_encrypt(v_raw::text, p_encryption_key, 'cipher-algo=aes256');

    INSERT INTO app.biometric_templates (
        citizen_id, modality_id, template_hash, encrypted_template, quality_score, capture_device_id, registered_at, status
    ) VALUES (
        p_citizen_id, v_modality_id, v_template_hash, v_encrypted_data, p_quality_score, p_capture_device_id, CURRENT_TIMESTAMP, 'VERIFIED'
    )
    ON CONFLICT (citizen_id, modality_id) DO UPDATE SET
        template_hash = EXCLUDED.template_hash,
        encrypted_template = EXCLUDED.encrypted_template,
        quality_score = EXCLUDED.quality_score,
        capture_device_id = EXCLUDED.capture_device_id,
        registered_at = CURRENT_TIMESTAMP,
        status = 'VERIFIED'
    RETURNING biometric_id INTO v_new_biometric_id;

    UPDATE app.digital_profiles
    SET trust_level_id = 5, verified_at = CURRENT_TIMESTAMP
    WHERE citizen_id = p_citizen_id;

    v_exec_ms := round((EXTRACT(EPOCH FROM (clock_timestamp() - v_start_time)) * 1000)::numeric, 3);
    PERFORM audit.fn_log_function_call(
        'app.fn_register_biometric_template',
        session_user,
        v_params,
        TRUE,
        NULL,
        v_exec_ms
    );

    RETURN v_new_biometric_id;
EXCEPTION WHEN OTHERS THEN
    v_exec_ms := round((EXTRACT(EPOCH FROM (clock_timestamp() - v_start_time)) * 1000)::numeric, 3);
    PERFORM audit.fn_log_function_call(
        'app.fn_register_biometric_template',
        session_user,
        v_params,
        FALSE,
        SQLERRM,
        v_exec_ms
    );
    RAISE;
END;
$$;

GRANT EXECUTE ON FUNCTION app.fn_register_biometric_template(BIGINT, VARCHAR, BYTEA, NUMERIC, VARCHAR, TEXT) TO app_writer, dml_admin;

-- 5. Перегрузка fn_grant_interagency_token
CREATE OR REPLACE FUNCTION app.fn_grant_interagency_token(
    p_profile_id BIGINT,
    p_agency_code VARCHAR,
    p_requested_scope VARCHAR,
    p_duration_hours INT
)
RETURNS VARCHAR
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = app, ref, audit, public, pg_temp
AS $$
DECLARE
    v_start_time TIMESTAMPTZ := clock_timestamp();
    v_exec_ms NUMERIC(10,3);
    v_agency_id INT;
    v_consent_id BIGINT;
    v_raw_token BYTEA;
    v_token_hash VARCHAR(64);
    v_params JSONB;
BEGIN
    v_params := jsonb_build_object(
        'profile_id', p_profile_id,
        'agency_code', p_agency_code,
        'requested_scope', p_requested_scope,
        'duration_hours', p_duration_hours
    );

    -- Проверка корректности scope
    IF p_requested_scope NOT IN ('PROFILE_READ', 'DOCS_VERIFY', 'BIOMETRIC_MATCH', 'FULL_ACCESS') THEN
        RAISE EXCEPTION 'Недопустимая область доступа (scope): %', p_requested_scope;
    END IF;

    -- Поиск ведомства
    SELECT agency_id INTO v_agency_id
    FROM ref.agencies
    WHERE agency_code = p_agency_code;

    IF v_agency_id IS NULL THEN
        RAISE EXCEPTION 'Ведомство с кодом % не зарегистрировано в системе', p_agency_code;
    END IF;

    -- Проверка действующего согласия
    SELECT consent_id INTO v_consent_id
    FROM app.access_consents
    WHERE profile_id = p_profile_id
      AND agency_id = v_agency_id
      AND scope = p_requested_scope
      AND is_revoked IS FALSE
      AND valid_until > CURRENT_TIMESTAMP;

    IF v_consent_id IS NULL THEN
        RAISE EXCEPTION 'Отсутствует действующее согласие гражданина % для ведомства % по scope %', p_profile_id, p_agency_code, p_requested_scope;
    END IF;

    -- Генерация криптографического токена
    v_raw_token := gen_random_bytes(32);
    v_token_hash := encode(digest(v_raw_token, 'sha256'), 'hex');

    INSERT INTO app.access_tokens (
        profile_id, agency_id, required_trust_level_id, token_hash, issued_at, expires_at, status
    ) VALUES (
        p_profile_id, v_agency_id, 1, v_token_hash,
        CURRENT_TIMESTAMP,
        CURRENT_TIMESTAMP + (p_duration_hours || ' hours')::interval,
        'ACTIVE'
    );

    v_exec_ms := round((EXTRACT(EPOCH FROM (clock_timestamp() - v_start_time)) * 1000)::numeric, 3);
    PERFORM audit.fn_log_function_call(
        'app.fn_grant_interagency_token',
        session_user,
        v_params,
        TRUE,
        NULL,
        v_exec_ms
    );

    RETURN 'tok_sec_' || substr(v_token_hash, 1, 24);
EXCEPTION WHEN OTHERS THEN
    v_exec_ms := round((EXTRACT(EPOCH FROM (clock_timestamp() - v_start_time)) * 1000)::numeric, 3);
    PERFORM audit.fn_log_function_call(
        'app.fn_grant_interagency_token',
        session_user,
        v_params,
        FALSE,
        SQLERRM,
        v_exec_ms
    );
    RAISE;
END;
$$;

GRANT EXECUTE ON FUNCTION app.fn_grant_interagency_token(BIGINT, VARCHAR, VARCHAR, INT) TO app_writer, dml_admin;
